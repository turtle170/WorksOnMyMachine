//! NoNet as an XLA compute graph (StableHLO, MLIR text), and its translation
//! into human-readable Python. Emit-only: nothing here needs XLA installed.

use anyhow::{bail, Context, Result};

use crate::nonet::{self, Nonet, B1, B2, B3, H1, H2, IN, W1, W2, W3};

fn fmt(v: f32) -> String {
    format!("{v:.9e}")
}

fn vector(v: &[f32]) -> String {
    format!("[{}]", v.iter().map(|x| fmt(*x)).collect::<Vec<_>>().join(", "))
}

fn matrix(v: &[f32], rows: usize, cols: usize) -> String {
    let rows: Vec<String> = (0..rows).map(|r| vector(&v[r * cols..(r + 1) * cols])).collect();
    format!("[{}]", rows.join(",\n      "))
}

fn act_fn(n: usize) -> String {
    let t = format!("tensor<{n}xf32>");
    format!(
        "  // rational tanh: x(27 + x^2) / (27 + 9x^2), clamped to [-3, 3]\n\
  func.func private @act{n}(%x: {t}) -> {t} {{\n\
    %lo = stablehlo.constant dense<-3.0> : {t}\n\
    %hi = stablehlo.constant dense<3.0> : {t}\n\
    %k27 = stablehlo.constant dense<27.0> : {t}\n\
    %k9 = stablehlo.constant dense<9.0> : {t}\n\
    %c = stablehlo.clamp %lo, %x, %hi : {t}\n\
    %x2 = stablehlo.multiply %c, %c : {t}\n\
    %t1 = stablehlo.add %k27, %x2 : {t}\n\
    %num = stablehlo.multiply %c, %t1 : {t}\n\
    %t2 = stablehlo.multiply %k9, %x2 : {t}\n\
    %den = stablehlo.add %k27, %t2 : {t}\n\
    %r = stablehlo.divide %num, %den : {t}\n\
    return %r : {t}\n\
  }}\n"
    )
}

/// The full module: NoNet's forward pass with its trained weights baked in as
/// constants, plus the big hash it was fed.
pub fn emit(net: &Nonet, big: &[u8]) -> String {
    let p = &net.p;
    let mut s = String::new();
    s.push_str(&format!(
        "// NoNet v0 -- {} parameters, {IN} -> {H1} -> {H2} -> 1. Generated by womm. Do not run.\n",
        nonet::PARAMS
    ));
    s.push_str(&format!("module @nonet attributes {{womm.params = {} : i64}} {{\n", nonet::PARAMS));
    s.push_str(&format!("  func.func public @main(%x: tensor<{IN}xf32>) -> tensor<f32> {{\n"));
    s.push_str(&format!(
        "    %w1 = stablehlo.constant dense<{}> : tensor<{IN}x{H1}xf32>\n",
        matrix(&p[W1..B1], IN, H1)
    ));
    s.push_str(&format!("    %b1 = stablehlo.constant dense<{}> : tensor<{H1}xf32>\n", vector(&p[B1..W2])));
    s.push_str(&format!(
        "    %d1 = stablehlo.dot_general %x, %w1, contracting_dims = [0] x [0] : (tensor<{IN}xf32>, tensor<{IN}x{H1}xf32>) -> tensor<{H1}xf32>\n"
    ));
    s.push_str(&format!("    %p1 = stablehlo.add %b1, %d1 : tensor<{H1}xf32>\n"));
    s.push_str(&format!("    %h1 = func.call @act{H1}(%p1) : (tensor<{H1}xf32>) -> tensor<{H1}xf32>\n"));
    s.push_str(&format!(
        "    %w2 = stablehlo.constant dense<{}> : tensor<{H1}x{H2}xf32>\n",
        matrix(&p[W2..B2], H1, H2)
    ));
    s.push_str(&format!("    %b2 = stablehlo.constant dense<{}> : tensor<{H2}xf32>\n", vector(&p[B2..W3])));
    s.push_str(&format!(
        "    %d2 = stablehlo.dot_general %h1, %w2, contracting_dims = [0] x [0] : (tensor<{H1}xf32>, tensor<{H1}x{H2}xf32>) -> tensor<{H2}xf32>\n"
    ));
    s.push_str(&format!("    %p2 = stablehlo.add %b2, %d2 : tensor<{H2}xf32>\n"));
    s.push_str(&format!("    %h2 = func.call @act{H2}(%p2) : (tensor<{H2}xf32>) -> tensor<{H2}xf32>\n"));
    s.push_str(&format!("    %w3 = stablehlo.constant dense<{}> : tensor<{H2}xf32>\n", vector(&p[W3..B3])));
    s.push_str(&format!("    %b3 = stablehlo.constant dense<{}> : tensor<f32>\n", fmt(p[B3])));
    s.push_str(&format!(
        "    %d3 = stablehlo.dot_general %h2, %w3, contracting_dims = [0] x [0] : (tensor<{H2}xf32>, tensor<{H2}xf32>) -> tensor<f32>\n"
    ));
    s.push_str("    %y = stablehlo.add %b3, %d3 : tensor<f32>\n");
    s.push_str("    return %y : tensor<f32>\n  }\n");
    s.push_str(&act_fn(H1));
    s.push_str(&act_fn(H2));
    s.push_str(&format!("  func.func public @big_hash() -> tensor<{}xui8> {{\n", big.len()));
    s.push_str(&format!(
        "    %h = stablehlo.constant dense<[{}]> : tensor<{}xui8>\n",
        big.iter().map(|b| b.to_string()).collect::<Vec<_>>().join(", "),
        big.len()
    ));
    s.push_str(&format!("    return %h : tensor<{}xui8>\n  }}\n}}\n", big.len()));
    s
}

/// Numbers inside `dense<...>` on the line that defines `%name`.
fn dense(module: &str, name: &str) -> Result<Vec<String>> {
    let start = module
        .find(&format!("%{name} = stablehlo.constant dense<"))
        .with_context(|| format!("StableHLO has no constant %{name}"))?;
    let open = module[start..].find("dense<").unwrap() + start + "dense<".len();
    let close = module[open..].find('>').context("unterminated dense<>")? + open;
    Ok(module[open..close]
        .split(|c: char| c == ',' || c == '[' || c == ']' || c.is_whitespace())
        .filter(|t| !t.is_empty())
        .map(String::from)
        .collect())
}

/// Recover NoNet and the big hash from a StableHLO module.
pub fn parse(module: &str) -> Result<(Nonet, Vec<u8>)> {
    let mut p = Vec::with_capacity(nonet::PARAMS);
    for name in ["w1", "b1", "w2", "b2", "w3", "b3"] {
        for t in dense(module, name)? {
            p.push(t.parse::<f32>().with_context(|| format!("bad weight {t:?} in %{name}"))?);
        }
    }
    if p.len() != nonet::PARAMS {
        bail!("StableHLO holds {} parameters, expected {}", p.len(), nonet::PARAMS);
    }
    let big = dense(module, "h")?
        .iter()
        .map(|t| t.parse::<u8>().with_context(|| format!("bad hash byte {t:?}")))
        .collect::<Result<Vec<u8>>>()?;
    Ok((Nonet { p }, big))
}

/// A faithful, stdlib-only Python rendition of the graph.
pub fn python(module: &str, source: &str) -> Result<String> {
    let (net, big) = parse(module)?;
    let p = &net.p;
    let py_vec = |v: &[f32]| format!("[{}]", v.iter().map(|x| fmt(*x)).collect::<Vec<_>>().join(", "));
    let py_mat = |v: &[f32], rows: usize, cols: usize| {
        let r: Vec<String> = (0..rows).map(|i| format!("    {},", py_vec(&v[i * cols..(i + 1) * cols]))).collect();
        format!("[\n{}\n]", r.join("\n"))
    };
    Ok(format!(
        r#"#!/usr/bin/env python3
"""NoNet v0, translated from the StableHLO in {source} by `womm visualise`.

833 parameters: 8 inputs -> 32 hidden -> 16 hidden -> 1 output.
Standard library only. Running this file prints the extra hash that womm
generated during `womm build`; it should match the manifest exactly, because
every operation below is rounded to 32-bit floats the same way womm does it.
"""
import struct


def f32(x):
    """Round to an IEEE-754 single-precision float, like womm's Rust code."""
    return struct.unpack("f", struct.pack("f", x))[0]


def weights(rows):
    return [[f32(v) for v in row] for row in rows]


# Layer 1: W1[input][hidden], 8 x 32, plus 32 biases.
W1 = weights({w1})
B1 = [f32(v) for v in {b1}]

# Layer 2: W2[hidden1][hidden2], 32 x 16, plus 16 biases.
W2 = weights({w2})
B2 = [f32(v) for v in {b2}]

# Layer 3: 16 weights and one bias.
W3 = [f32(v) for v in {w3}]
B3 = f32({b3})

# The big hash: four RSA-2048 signatures, concatenated (1024 bytes).
BIG_HASH = bytes.fromhex(
    "{big}"
)


def act(x):
    """Rational tanh: x(27 + x^2) / (27 + 9x^2), clamped to [-3, 3]."""
    x = min(max(x, -3.0), 3.0)
    x2 = f32(x * x)
    num = f32(x * f32(27.0 + x2))
    den = f32(27.0 + f32(9.0 * x2))
    return f32(num / den)


def nonet(window):
    """One forward pass. Eight bytes in, one opinion out."""
    x = [f32(f32(b / 255.0) - 0.5) for b in window]
    h1 = []
    for j in range(32):
        acc = B1[j]
        for i in range(8):
            acc = f32(acc + f32(x[i] * W1[i][j]))
        h1.append(act(acc))
    h2 = []
    for k in range(16):
        acc = B2[k]
        for j in range(32):
            acc = f32(acc + f32(h1[j] * W2[j][k]))
        h2.append(act(acc))
    y = B3
    for k in range(16):
        y = f32(y + f32(h2[k] * W3[k]))
    return y


def extra_hash(big):
    """Slide an 8-byte window over the big hash until NoNet says stop."""
    out = []
    for w in range(min(len(big) // 8, 128)):
        window = big[w * 8:(w + 1) * 8]
        v = int(f32(nonet(window) * 65536.0))
        out.append((v & 0xFF) ^ window[w % 8])
        if len(out) >= 16 and ((v >> 8) & 0x1F) == 0:
            break
    return bytes(out)


if __name__ == "__main__":
    print(extra_hash(BIG_HASH).hex())
"#,
        w1 = py_mat(&p[W1..B1], IN, H1),
        b1 = py_vec(&p[B1..W2]),
        w2 = py_mat(&p[W2..B2], H1, H2),
        b2 = py_vec(&p[B2..W3]),
        w3 = py_vec(&p[W3..B3]),
        b3 = fmt(p[B3]),
        big = hex::encode(&big),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips_weights_exactly() {
        let net = Nonet::untrained(b"hlo");
        let big: Vec<u8> = (0..1024u32).map(|i| (i % 256) as u8).collect();
        let module = emit(&net, &big);
        assert_eq!(module.matches("stablehlo.dot_general").count(), 3);
        let (back, b) = parse(&module).unwrap();
        assert_eq!(back.p, net.p);
        assert_eq!(b, big);
        assert_eq!(back.extra_hash(&big), net.extra_hash(&big));
        assert!(python(&module, "x.womm.md").unwrap().contains("def nonet(window)"));
    }
}
