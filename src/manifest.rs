//! Stage 2 (`build`): kludge objects -> `.womm.md` build manifest.
//! Stage 3 (`parsy-builder`): manifest -> native executable.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use base64::{engine::general_purpose::STANDARD, Engine};

use crate::kludge::{self, sha256_hex};
use crate::payload::{self, Program};

pub const MAGIC_LINE: &str = "<!-- womm-manifest v1 -->";
const BEGIN: &str = "<!-- womm:binary:begin -->";
const END: &str = "<!-- womm:binary:end -->";

pub fn host_target() -> String {
    format!("{}-{}", std::env::consts::OS, std::env::consts::ARCH)
}

pub fn build(dir: &Path) -> Result<()> {
    let (hdr, source) = kludge::load(dir)?;
    let stem = hdr
        .source_name
        .strip_suffix(".womm")
        .unwrap_or(&hdr.source_name)
        .to_string();

    println!("   Compiling {} kludge object(s) from {}", hdr.total, dir.display());
    let program = Program {
        name: stem.clone(),
        source_sha256: hdr.source_sha256.clone(),
        opt_level: hdr.opt_level,
        kludge_count: hdr.total,
        built_with: format!("womm {}", env!("CARGO_PKG_VERSION")),
        plan: String::from_utf8(source).context("reassembled source is not UTF-8")?,
    };
    let exe = payload::assemble(&payload::base_stub()?, &program)?;
    let b64 = STANDARD.encode(&exe);

    let mut md = String::new();
    md.push_str(MAGIC_LINE);
    md.push_str(&format!("\n# Build Manifest: {stem}\n\n"));
    md.push_str("> Generated by womm. This document is the build output. Do not edit.\n\n");
    md.push_str("## Parameters\n\n| Key | Value |\n|---|---|\n");
    for (k, v) in [
        ("source", hdr.source_name.as_str()),
        ("source_sha256", &hdr.source_sha256),
        ("parser_opt_level", &hdr.opt_level.to_string()),
        ("kludge_count", &hdr.total.to_string()),
        ("target", &host_target()),
        ("binary_size", &exe.len().to_string()),
        ("binary_sha256", &sha256_hex(&exe)),
        ("compiler", &program.built_with),
    ] {
        md.push_str(&format!("| {k} | `{v}` |\n"));
    }
    md.push_str("\n## Binary\n\n");
    md.push_str(BEGIN);
    md.push_str("\n```base64\n");
    for line in b64.as_bytes().chunks(76) {
        md.push_str(std::str::from_utf8(line).unwrap());
        md.push('\n');
    }
    md.push_str("```\n");
    md.push_str(END);
    md.push('\n');

    let out = dir
        .parent()
        .unwrap_or(Path::new("."))
        .join(format!("{stem}.womm.md"));
    fs::write(&out, md).with_context(|| format!("could not write {}", out.display()))?;
    println!("   Wrote build manifest {} ({} bytes of binary)", out.display(), exe.len());
    println!("    Finished. Next: womm parsy-builder {}", out.display());
    Ok(())
}

fn param(text: &str, key: &str) -> Option<String> {
    text.lines().find_map(|l| {
        let cells: Vec<&str> = l.split('|').map(str::trim).collect();
        (cells.len() >= 3 && cells[1] == key).then(|| cells[2].trim_matches('`').to_string())
    })
}

pub fn link(manifest: &Path, output: Option<PathBuf>) -> Result<()> {
    let text = fs::read_to_string(manifest)
        .with_context(|| format!("could not read {}", manifest.display()))?;
    if text.lines().next() != Some(MAGIC_LINE) {
        bail!("{} is not a womm build manifest", manifest.display());
    }

    let target = param(&text, "target").context("manifest has no target")?;
    if target != host_target() {
        bail!(
            "manifest targets `{target}` but this machine is `{}`. It worked on the machine that built it.",
            host_target()
        );
    }
    let expected = param(&text, "binary_sha256").context("manifest has no binary_sha256")?;

    let start = text.find(BEGIN).context("manifest has no binary section")? + BEGIN.len();
    let end = text[start..].find(END).context("manifest binary section is unterminated")? + start;
    let b64: String = text[start..end]
        .lines()
        .filter(|l| !l.trim_start().starts_with("```"))
        .map(str::trim)
        .collect();
    let exe = STANDARD.decode(b64).context("manifest binary is not valid base64")?;
    if sha256_hex(&exe) != expected {
        bail!("binary does not match binary_sha256; the manifest has been tampered with (or edited)");
    }

    let out = output.unwrap_or_else(|| {
        let name = manifest.file_name().and_then(|n| n.to_str()).unwrap_or("a.out");
        let stem = name
            .strip_suffix(".womm.md")
            .or_else(|| name.strip_suffix(".md"))
            .unwrap_or(name);
        let file = format!("{stem}{}", std::env::consts::EXE_SUFFIX);
        manifest.parent().unwrap_or(Path::new(".")).join(file)
    });
    fs::write(&out, &exe).with_context(|| format!("could not write {}", out.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&out, fs::Permissions::from_mode(0o755))?;
    }
    println!("   Linked {} ({} bytes, {target})", out.display(), exe.len());
    println!("    Finished. Your project is now executable.");
    Ok(())
}
