//! Stage 1: `.womm` source -> `.kludge` intermediate objects.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use base64::{engine::general_purpose::STANDARD, Engine};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::gags;
use crate::grammar::Ctx;
use crate::nonet::Voice;

pub const FORMAT: u32 = 1;
const BASE_FRAGMENTS: u32 = 4;

#[derive(Serialize, Deserialize, Clone)]
pub struct Header {
    pub format: u32,
    pub index: u32,
    pub total: u32,
    pub opt_level: u8,
    pub source_name: String,
    pub source_sha256: String,
    pub womm_version: String,
}

#[derive(Serialize, Deserialize)]
pub struct Fragment {
    pub checksum: String,
    pub data: String,
}

#[derive(Serialize, Deserialize)]
pub struct Kludge {
    pub kludge: Header,
    pub payload: Fragment,
}

pub fn sha256_hex(bytes: &[u8]) -> String {
    hex::encode(Sha256::digest(bytes))
}

/// Number of kludge objects for an opt level: 4, 16, 64, 256.
pub fn fragment_count(opt: u8) -> u32 {
    BASE_FRAGMENTS * 4u32.pow(opt as u32)
}

pub fn kludged_dir_for(file: &Path, stem: &str) -> PathBuf {
    file.parent()
        .unwrap_or(Path::new("."))
        .join(format!("{stem}.kludged"))
}

pub fn parse(file: &Path, opt: u8, quiet_warnings: bool) -> Result<()> {
    if opt > 3 {
        bail!("-O{opt} is reserved for the machine");
    }
    let name = file
        .file_name()
        .and_then(|n| n.to_str())
        .context("source path has no usable file name")?
        .to_string();
    let Some(stem) = name.strip_suffix(".womm") else {
        bail!("unrecognised source extension for `{name}` (expected <name>.womm)");
    };
    if stem.is_empty() {
        bail!("source file name `{name}` has no name before .womm");
    }

    let bytes = fs::read(file).with_context(|| format!("could not read {}", file.display()))?;
    let Ok(text) = std::str::from_utf8(&bytes) else {
        bail!("{name} is not valid UTF-8; womm only accepts Unicode project plans");
    };

    let source_sha256 = sha256_hex(&bytes);
    let key = crate::keys::machine_key()?;
    let mut voice = Voice::new(&gags::parse_seed(&crate::keys::public_der(&key), &source_sha256));
    let ctx = Ctx::from_text(text);

    let dir = kludged_dir_for(file, stem);
    prepare_dir(&dir)?;
    let total = fragment_count(opt);

    println!("   Parsing {name} (parser opt-level {opt})");
    gags::opt_passes(&mut voice, &ctx, opt);
    emit(&dir, &name, &bytes, total, opt)?;
    println!("   Emitted {total} kludge object(s) into {}", dir.display());
    println!("   Source integrity sha256:{source_sha256}");

    let ws = gags::warnings(&mut voice, text, opt);
    gags::print_warnings(&ws, None, quiet_warnings);
    gags::o3_aftermath(total, opt);
    println!("    Finished. Next: womm build {}", dir.display());
    Ok(())
}

/// Split `bytes` into `total` kludge objects inside `dir`.
pub fn emit(dir: &Path, source_name: &str, bytes: &[u8], total: u32, opt: u8) -> Result<()> {
    let source_sha256 = sha256_hex(bytes);
    let chunk = (bytes.len() as u32).div_ceil(total).max(1) as usize;
    for i in 0..total {
        let start = (i as usize * chunk).min(bytes.len());
        let end = ((i as usize + 1) * chunk).min(bytes.len());
        let slice = &bytes[start..end];
        let k = Kludge {
            kludge: Header {
                format: FORMAT,
                index: i,
                total,
                opt_level: opt,
                source_name: source_name.to_string(),
                source_sha256: source_sha256.clone(),
                womm_version: env!("CARGO_PKG_VERSION").to_string(),
            },
            payload: Fragment {
                checksum: sha256_hex(slice),
                data: STANDARD.encode(slice),
            },
        };
        let body = format!(
            "# KLUDGE OBJECT -- generated by womm {}. DO NOT EDIT.\n# Editing this file voids the warranty, which does not exist.\n\n{}",
            env!("CARGO_PKG_VERSION"),
            toml::to_string(&k)?
        );
        let file_name = format!("{i:04}-{}.kludge", &k.payload.checksum[..8]);
        fs::write(dir.join(file_name), body)?;
    }
    Ok(())
}

/// Create the output dir, removing stale .kludge files from an earlier parse.
pub fn prepare_dir(dir: &Path) -> Result<()> {
    if dir.exists() {
        for entry in fs::read_dir(dir)? {
            let path = entry?.path();
            if path.extension().is_some_and(|e| e == "kludge") {
                fs::remove_file(path)?;
            }
        }
    }
    fs::create_dir_all(dir).with_context(|| format!("could not create {}", dir.display()))
}

/// Read every .kludge in `dir`, validate, and reassemble the original source.
/// Also returns the raw bytes of each kludge object, in index order.
pub fn load(dir: &Path) -> Result<(Header, Vec<u8>, Vec<Vec<u8>>)> {
    let mut kludges = Vec::new();
    for entry in fs::read_dir(dir).with_context(|| format!("could not read {}", dir.display()))? {
        let path = entry?.path();
        if path.extension().is_some_and(|e| e == "kludge") {
            let text = fs::read_to_string(&path)?;
            let k: Kludge = toml::from_str(&text)
                .with_context(|| format!("corrupt kludge object {}", path.display()))?;
            kludges.push((k, text.into_bytes()));
        }
    }
    if kludges.is_empty() {
        bail!("no .kludge objects found in {} (did you run `womm parse`?)", dir.display());
    }

    kludges.sort_by_key(|(k, _)| k.kludge.index);
    let first = kludges[0].0.kludge.clone();
    if first.format != FORMAT {
        bail!("unsupported kludge format {}", first.format);
    }
    if kludges.len() as u32 != first.total {
        bail!(
            "expected {} kludge objects, found {} (some kludge has gone missing)",
            first.total,
            kludges.len()
        );
    }

    let mut source = Vec::new();
    for (i, (k, _)) in kludges.iter().enumerate() {
        let h = &k.kludge;
        if h.index != i as u32 || h.total != first.total || h.source_sha256 != first.source_sha256 {
            bail!("kludge object {} does not belong to this build", h.index);
        }
        let bytes = STANDARD.decode(&k.payload.data)?;
        if sha256_hex(&bytes) != k.payload.checksum {
            bail!("kludge object {} failed its checksum", h.index);
        }
        source.extend_from_slice(&bytes);
    }
    if sha256_hex(&source) != first.source_sha256 {
        bail!("reassembled source does not match its recorded sha256");
    }
    let raw = kludges.into_iter().map(|(_, r)| r).collect();
    Ok((first, source, raw))
}
